const SIGNAL = 'rgb(232 185 49)'

// The <style> of one art file: every role, resolved for one hour
export function artStyle(scene, hour) {
  const inks = PALETTES[scene]
  const i = hour === 'night' ? 1 : 0
  return Object.entries(ROLES)
    .map(([cls, decls]) => {
      const body = decls
        .map(([prop, token]) => {
          if (token === 'none') return `${prop}:none`
          if (token === 'color-signal') return `${prop}:${SIGNAL}`
          return inks[token] ? `${prop}:${inks[token][i]}` : null
        })
        .filter(Boolean)
      return body.length === decls.length ? `.${cls}{${body.join(';')}}` : null
    })
    .filter(Boolean)
    .join('')
}
